#pragma once

#include <string>
#include <vector>

// ─────────────────────────────────────────────────────────────
//  Volume_Mapper — 通道音量（CC7）映射
//  职责：把通道 1 的 CC7 消息读成"通道音量时间线"。
//  只看 CC7 —— 不看音符、不看弯音、不看 CC11，是纯粹的 时间 → 音量值 函数。
//
//  坐标约定（本模块自己换算完，不把 PPQN 泄漏给调用者）：
//      横轴 = 四分音符数（PPQN 只在本模块内部用一次）
//      纵轴 = CC7 值（int，0..127 的 MIDI 7 位量）
//
//  CC7 是"等比"系数：模拟响度 = velo × CC7(t)/100 × CC11(t)/100。
//  所以 CC7 = 0 会让整条曲线塌成零增益、也失去等比含义 ——
//  与 velocity = 0 一样，这类事件被识别出来后**不采纳**（整条丢掉）。
//
//  ⚠️ 这是**解析**侧：读输入文件里真实存在的 CC7。
//     与协议 7.3「通道音量（CC7）」是两件事 —— 那边规定的是**输出**行为
//     （不读取输入 CC7、按声部表值重写、每通道固定一个值、tick 0 写一次），
//     不适用于本模块。本模块只回答"输入文件在这个时刻把 CC7 设成了多少"。
//
//  解析规则（与 Expression_Mapper 同款）：
//      - 只读取所选输入通道的 CC7
//      - 同一 tick 多次生效：后写覆盖前写
//      - 若输入无 CC7，时间线仅含 tick 0 的默认值 100
//      - 首条事件 tick > 0 → 在 tick 0 补一条默认值 100
//      - 采样保持：没有新消息时值不变（画曲线要画阶梯，不能连直线）
// ─────────────────────────────────────────────────────────────

namespace VOL {

	/// 通道音量时间线上的一个采样点。
	struct Point {
		double quarters = 0.0;   ///< 从曲首起的四分音符数
		int    value    = 100;   ///< 该点起的 CC7 值（1..127）
	};

	/// 通道 1 的通道音量时间线。
	struct Curve {
		int    channel       = 1;     ///< MIDI 通道号（本工具只处理 1）
		double quartersBegin = 0.0;   ///< 覆盖范围起点（四分音符）
		double quartersEnd   = 0.0;   ///< 覆盖范围终点（四分音符）
		std::vector<Point> points;    ///< 采样点，按时间升序；首点恒在 tick 0
	};

	/// 探测结果。
	struct Result {
		bool        ok = false;   ///< 是否成功解析
		Curve       curve;        ///< 通道音量时间线
		std::string message;      ///< 可直接显示的一句话
	};

	/// 默认通道音量值。
	/// ⚠️ 取 100 是**显示模型**的口径（基准 = 100，即等比系数 1.0），
	///    不是协议 7.3 表里的 CC7_F0 = 100（那是个巧合的数值撞车，
	///    两者语义无关：一个是"输入文件没写 CC7 时的中性系数"，
	///    一个是"输出 Voice 轨 F0 声部的表值"）。
	const int kDefaultValue = 100;

	/// 解析通道 1 的 CC7，生成通道音量时间线。
	Result VM(const std::string& path);

	/// 查询某个四分音符位置上的 CC7 值（采样保持语义）。
	/// 第一个事件之前 → kDefaultValue。纯查询：无依赖、无副作用。
	int ValueAt(const Curve& curve, double quarters);

}
